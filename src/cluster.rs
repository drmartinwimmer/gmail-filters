use crate::classify::{SanitizedEmailEnvelope, UntrustedEmailInput, sanitize_untrusted_email};
use crate::tier1::{SenderEngagementMetrics, UnsubscribeCapability};
use crate::{GmailTriageError, StructuralFilterCriteria, build_cluster_filter_criteria};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// Normalized representation of a single Gmail message fetched via `gws`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FetchedGmailMessage {
    /// Gmail message ID.
    pub id: String,
    /// Verified sender email address (`From` header, normalized to lowercase email).
    pub from_address: String,
    /// Optional recipient address (`To` header, normalized to lowercase email).
    pub to_address: Option<String>,
    /// Optional `List-Id` identifier (extracted from `<...>` or raw header).
    pub list_id: Option<String>,
    /// Detected `List-Unsubscribe` / RFC 8058 capability.
    pub unsubscribe: UnsubscribeCapability,
    /// Whether `Precedence: bulk` or `Precedence: list` was present.
    pub precedence_bulk: bool,
    /// Whether the message is currently unread (`UNREAD` label present).
    pub is_unread: bool,
    /// Whether the message is currently in the primary inbox (`INBOX` label present).
    pub in_inbox: bool,
    /// Raw untrusted `Subject` header.
    pub raw_subject: String,
    /// Raw untrusted snippet or body text.
    pub raw_snippet: String,
}

/// Composite key that groups messages from the same sender into distinct functional streams
/// (e.g. separating receipts vs. marketing vs. security alerts from the same domain/sender).
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub struct ClusterKey {
    /// Verified sender email address (`from`).
    pub from_address: String,
    /// Optional mailing list identifier (`list`).
    pub list_id: Option<String>,
    /// Optional recipient address (`to`).
    pub to_address: Option<String>,
    /// Optional normalized structural subject prefix or bracket tag (e.g. `[ billing ]` or `Invoice`).
    pub subject_prefix: Option<String>,
}

impl ClusterKey {
    /// Converts this `ClusterKey` into a validated `StructuralFilterCriteria` (`From`, `List`, or compound `And`).
    pub fn to_filter_criteria(&self) -> StructuralFilterCriteria {
        build_cluster_filter_criteria(
            &self.from_address,
            self.list_id.as_deref(),
            self.to_address.as_deref(),
            self.subject_prefix.as_deref(),
        )
    }
}

/// Aggregated cluster of messages sharing a `ClusterKey`, ready for Tier 1 / Tier 2 triage.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct EmailCluster {
    /// Structural key identifying this cluster.
    pub key: ClusterKey,
    /// Aggregated deterministic engagement metrics for Tier 1 analysis.
    pub engagement: SenderEngagementMetrics,
    /// Sanitized representative sample envelope for quarantined Tier 2 local LLM classification.
    pub representative_sample: SanitizedEmailEnvelope,
}

/// Raw JSON response from `gws gmail users messages list`.
#[derive(Debug, Clone, Deserialize)]
pub struct GwsMessageListResponse {
    /// Page of message stubs.
    #[serde(default)]
    pub messages: Vec<GwsMessageStub>,
}

/// Message stub returned by `gws gmail users messages list`.
#[derive(Debug, Clone, Deserialize)]
pub struct GwsMessageStub {
    /// Gmail message ID.
    pub id: String,
}

/// Raw JSON response from `gws gmail users messages get`.
#[derive(Debug, Clone, Deserialize)]
pub struct GwsMessageResource {
    /// Gmail message ID.
    pub id: String,
    /// Applied Gmail system/user label IDs (`UNREAD`, `INBOX`, etc.).
    #[serde(default, rename = "labelIds")]
    pub label_ids: Vec<String>,
    /// Short text snippet generated by Gmail.
    #[serde(default)]
    pub snippet: String,
    /// MIME payload containing headers.
    #[serde(default)]
    pub payload: Option<GwsMessagePayload>,
}

/// MIME payload inside `GwsMessageResource`.
#[derive(Debug, Clone, Default, Deserialize)]
pub struct GwsMessagePayload {
    /// MIME headers (`From`, `To`, `Subject`, `List-Id`, `List-Unsubscribe`, etc.).
    #[serde(default)]
    pub headers: Vec<GwsHeader>,
}

/// Single MIME header key/value pair.
#[derive(Debug, Clone, Deserialize)]
pub struct GwsHeader {
    /// Header name.
    pub name: String,
    /// Header value.
    pub value: String,
}

/// Parses a `GwsMessageResource` JSON string into a normalized `FetchedGmailMessage`.
pub fn parse_gws_message_json(raw_json: &str) -> Result<FetchedGmailMessage, GmailTriageError> {
    let resource: GwsMessageResource = serde_json::from_str(raw_json)
        .map_err(|err| GmailTriageError::GwsParseError(err.to_string()))?;
    convert_gws_resource(resource)
}

/// Converts a parsed `GwsMessageResource` into a `FetchedGmailMessage`.
pub fn convert_gws_resource(
    resource: GwsMessageResource,
) -> Result<FetchedGmailMessage, GmailTriageError> {
    let headers = resource.payload.map(|p| p.headers).unwrap_or_default();

    let raw_from = find_header(&headers, "From").ok_or_else(|| {
        GmailTriageError::GwsParseError(format!("Message '{}' missing From header", resource.id))
    })?;
    let from_address = extract_email_address(raw_from);
    if from_address.is_empty() {
        return Err(GmailTriageError::GwsParseError(format!(
            "Message '{}' has empty From address",
            resource.id
        )));
    }

    let to_address = find_header(&headers, "To")
        .map(extract_email_address)
        .filter(|s| !s.is_empty());
    let list_id = find_header(&headers, "List-Id")
        .map(extract_list_id)
        .filter(|s| !s.is_empty());

    let has_list_unsub = find_header(&headers, "List-Unsubscribe").is_some();
    let has_one_click = find_header(&headers, "List-Unsubscribe-Post")
        .is_some_and(|val| val.to_ascii_lowercase().contains("one-click"));
    let unsubscribe = if has_one_click && has_list_unsub {
        UnsubscribeCapability::OneClickRfc8058
    } else if has_list_unsub {
        UnsubscribeCapability::HeaderPresent
    } else {
        UnsubscribeCapability::None
    };

    let precedence_bulk = find_header(&headers, "Precedence").is_some_and(|val| {
        let lower = val.trim().to_ascii_lowercase();
        lower == "bulk" || lower == "list" || lower == "junk"
    });

    let is_unread = resource.label_ids.iter().any(|l| l == "UNREAD");
    let in_inbox = resource.label_ids.iter().any(|l| l == "INBOX");
    let raw_subject = find_header(&headers, "Subject").unwrap_or("").to_string();

    Ok(FetchedGmailMessage {
        id: resource.id,
        from_address,
        to_address,
        list_id,
        unsubscribe,
        precedence_bulk,
        is_unread,
        in_inbox,
        raw_subject,
        raw_snippet: resource.snippet,
    })
}

/// Groups a slice of `FetchedGmailMessage` items into sub-clusters keyed by
/// `(from_address, list_id, to_address, subject_prefix)` so that distinct email streams from the
/// same sender (e.g., receipts vs. newsletters vs. alerts) are triaged separately.
pub fn cluster_messages(messages: &[FetchedGmailMessage]) -> Vec<EmailCluster> {
    let mut grouped: BTreeMap<ClusterKey, Vec<&FetchedGmailMessage>> = BTreeMap::new();
    for msg in messages {
        let key = ClusterKey {
            from_address: msg.from_address.clone(),
            list_id: msg.list_id.clone(),
            to_address: msg.to_address.clone(),
            subject_prefix: extract_structural_subject_prefix(&msg.raw_subject),
        };
        grouped.entry(key).or_default().push(msg);
    }

    let mut clusters = Vec::with_capacity(grouped.len());
    for (key, group) in grouped {
        let mut total_received: u32 = 0;
        let mut opened_count: u32 = 0;
        let mut archived_unread_count: u32 = 0;
        let mut unsubscribe = UnsubscribeCapability::None;
        let mut precedence_bulk = false;

        for msg in &group {
            total_received = total_received.saturating_add(1);
            if !msg.is_unread {
                opened_count = opened_count.saturating_add(1);
            } else if !msg.in_inbox {
                archived_unread_count = archived_unread_count.saturating_add(1);
            }
            if msg.unsubscribe == UnsubscribeCapability::OneClickRfc8058
                || (msg.unsubscribe == UnsubscribeCapability::HeaderPresent
                    && unsubscribe == UnsubscribeCapability::None)
            {
                unsubscribe = msg.unsubscribe;
            }
            if msg.precedence_bulk {
                precedence_bulk = true;
            }
        }

        let sample_msg = group.first().copied();
        let representative_sample = match sample_msg {
            Some(first) => sanitize_untrusted_email(&UntrustedEmailInput {
                from: first.from_address.clone(),
                list_id: first.list_id.clone(),
                raw_subject: first.raw_subject.clone(),
                raw_body: first.raw_snippet.clone(),
            }),
            None => SanitizedEmailEnvelope {
                from: key.from_address.clone(),
                list_id: key.list_id.clone(),
                sanitized_subject: String::new(),
                sanitized_body_snippet: String::new(),
            },
        };

        let engagement = SenderEngagementMetrics {
            from: key.from_address.clone(),
            list_id: key.list_id.clone(),
            unsubscribe,
            precedence_bulk,
            total_received,
            opened_count,
            archived_unread_count,
        };

        clusters.push(EmailCluster {
            key,
            engagement,
            representative_sample,
        });
    }

    clusters
}

/// Extracts a safe structural subject prefix (such as a bracketed tag `[GitHub]` or well-known
/// stream keyword like `Invoice`, `Receipt`, `Security`, `Newsletter`) so different streams from
/// the same sender split into distinct sub-clusters without injecting arbitrary untrusted text.
pub fn extract_structural_subject_prefix(raw_subject: &str) -> Option<String> {
    let trimmed = raw_subject.trim();
    if let Some(rest) = trimmed.strip_prefix('[')
        && let Some((tag, _)) = rest.split_once(']')
    {
        let clean_tag: String = tag
            .trim()
            .chars()
            .filter(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '-' | '_'))
            .take(24)
            .collect();
        if !clean_tag.is_empty() {
            return Some(clean_tag);
        }
    }

    let lower = trimmed.to_ascii_lowercase();
    for keyword in [
        "invoice",
        "receipt",
        "statement",
        "order",
        "security",
        "alert",
        "verification",
        "newsletter",
        "digest",
        "weekly",
    ] {
        if lower.contains(keyword) {
            return Some(keyword.to_string());
        }
    }
    None
}

fn find_header<'a>(headers: &'a [GwsHeader], name: &str) -> Option<&'a str> {
    headers
        .iter()
        .find(|h| h.name.eq_ignore_ascii_case(name))
        .map(|h| h.value.as_str())
}

fn extract_email_address(raw: &str) -> String {
    let candidate = if let Some((_, after_lt)) = raw.rsplit_once('<')
        && let Some((inside, _)) = after_lt.split_once('>')
    {
        inside.trim()
    } else {
        raw.trim()
    };
    candidate
        .chars()
        .filter(|ch| !ch.is_whitespace() && !matches!(ch, '\'' | '"' | '<' | '>'))
        .collect::<String>()
        .to_ascii_lowercase()
}

fn extract_list_id(raw: &str) -> String {
    let candidate = if let Some((_, after_lt)) = raw.rsplit_once('<')
        && let Some((inside, _)) = after_lt.split_once('>')
    {
        inside.trim()
    } else {
        raw.trim()
    };
    candidate
        .chars()
        .filter(|ch| !ch.is_whitespace() && !matches!(ch, '\'' | '"' | '<' | '>'))
        .collect::<String>()
        .to_ascii_lowercase()
}

#[cfg(test)]
mod tests {
    use super::*;
    use googletest::prelude::*;

    #[googletest::test]
    fn parse_gws_message_json_extracts_headers_and_labels() -> Result<(), GmailTriageError> {
        let sample_json = r#"{
            "id": "msg-101",
            "labelIds": ["UNREAD"],
            "snippet": "Your monthly invoice #1042 is attached.",
            "payload": {
                "headers": [
                    {"name": "From", "value": "Acme Billing <Billing@Service.Example.com>"},
                    {"name": "To", "value": "User <user@example.com>"},
                    {"name": "Subject", "value": "Invoice #1042 for October"},
                    {"name": "List-Unsubscribe", "value": "<https://service.example.com/unsub>"},
                    {"name": "List-Unsubscribe-Post", "value": "List-Unsubscribe=One-Click"},
                    {"name": "Precedence", "value": "bulk"}
                ]
            }
        }"#;
        let msg = parse_gws_message_json(sample_json)?;
        assert_that!(msg.id, eq("msg-101"));
        assert_that!(msg.from_address, eq("billing@service.example.com"));
        assert_that!(msg.to_address, eq(&Some("user@example.com".to_string())));
        assert_that!(msg.unsubscribe, eq(UnsubscribeCapability::OneClickRfc8058));
        assert_that!(msg.precedence_bulk, is_true());
        assert_that!(msg.is_unread, is_true());
        assert_that!(msg.in_inbox, is_false());
        Ok(())
    }

    #[googletest::test]
    fn cluster_messages_splits_same_sender_by_subject_stream() {
        let messages = vec![
            FetchedGmailMessage {
                id: "1".to_string(),
                from_address: "updates@service.example.com".to_string(),
                to_address: Some("user@example.com".to_string()),
                list_id: None,
                unsubscribe: UnsubscribeCapability::None,
                precedence_bulk: false,
                is_unread: false,
                in_inbox: true,
                raw_subject: "Your Invoice #100".to_string(),
                raw_snippet: "Thank you for your payment.".to_string(),
            },
            FetchedGmailMessage {
                id: "2".to_string(),
                from_address: "updates@service.example.com".to_string(),
                to_address: Some("user@example.com".to_string()),
                list_id: None,
                unsubscribe: UnsubscribeCapability::HeaderPresent,
                precedence_bulk: true,
                is_unread: true,
                in_inbox: false,
                raw_subject: "Monthly Newsletter Update".to_string(),
                raw_snippet: "Check out our latest features.".to_string(),
            },
        ];

        let clusters = cluster_messages(&messages);
        assert_that!(clusters.len(), eq(2));
        assert_that!(
            clusters
                .first()
                .and_then(|c| c.key.subject_prefix.as_deref()),
            eq(Some("invoice"))
        );
        assert_that!(
            clusters
                .get(1)
                .and_then(|c| c.key.subject_prefix.as_deref()),
            eq(Some("newsletter"))
        );
    }
}
